CREATE TABLE dbo.AdminUsers (
  AdminId INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  Email NVARCHAR(254) NOT NULL UNIQUE,
  DisplayName NVARCHAR(150) NOT NULL,
  PasswordHash NVARCHAR(100) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_AdminUsers_CreatedAt DEFAULT SYSUTCDATETIME()
);

CREATE TABLE dbo.ContentRecords (
  RecordType NVARCHAR(30) NOT NULL,
  RecordId NVARCHAR(150) NOT NULL,
  DataJson NVARCHAR(MAX) NOT NULL,
  UpdatedAt DATETIME2 NOT NULL CONSTRAINT DF_ContentRecords_UpdatedAt DEFAULT SYSUTCDATETIME(),
  CONSTRAINT PK_ContentRecords PRIMARY KEY (RecordType, RecordId),
  CONSTRAINT CK_ContentRecords_Type CHECK (RecordType IN ('job', 'article'))
);

CREATE TABLE dbo.AppSettings (
  SettingsId INT NOT NULL PRIMARY KEY CONSTRAINT CK_AppSettings_Singleton CHECK (SettingsId = 1),
  DataJson NVARCHAR(MAX) NOT NULL,
  UpdatedAt DATETIME2 NOT NULL CONSTRAINT DF_AppSettings_UpdatedAt DEFAULT SYSUTCDATETIME()
);

CREATE TABLE dbo.Notifications (
  NotificationId NVARCHAR(100) NOT NULL PRIMARY KEY,
  DataJson NVARCHAR(MAX) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Notifications_CreatedAt DEFAULT SYSUTCDATETIME()
);

CREATE TABLE dbo.Quotes (
  SubmissionId BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  DataJson NVARCHAR(MAX) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Quotes_CreatedAt DEFAULT SYSUTCDATETIME()
);

CREATE TABLE dbo.Inquiries (
  SubmissionId BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  DataJson NVARCHAR(MAX) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Inquiries_CreatedAt DEFAULT SYSUTCDATETIME()
);

CREATE TABLE dbo.JobApplications (
  SubmissionId BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
  DataJson NVARCHAR(MAX) NOT NULL,
  CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_JobApplications_CreatedAt DEFAULT SYSUTCDATETIME()
);